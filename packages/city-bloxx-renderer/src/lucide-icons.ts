export function lucideSvg(name: LucideIconName, size = 16, className = ""): string {
  const cls = ["lucide", `lucide-${name}`, "cb-icon", className].filter(Boolean).join(" ");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="${cls}" aria-hidden="true">${LUCIDE_PATHS[name]}</svg>`;
}

export function createLucideElement(name: LucideIconName, size = 16, className = ""): SVGSVGElement {
  const wrap = document.createElement("span");
  wrap.innerHTML = lucideSvg(name, size, className);
  return wrap.firstElementChild as SVGSVGElement;
}
